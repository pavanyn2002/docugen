/**
 * External services this system talks to.
 *
 * Derived from two independent signals — an imported SDK, and an environment
 * variable named after a provider. Each edge records which signal produced it,
 * so a reader can tell a proven dependency from a strong hint.
 */
export function renderIntegrations(args: {
  deps: DepsResult | undefined;
  config: ConfigResult | undefined;
  projectName: string;
}): string {
  const services = new Map<string, Set<string>>();

  const add = (service: string, evidence: string): void => {
    const bucket = services.get(service) ?? new Set<string>();
    bucket.add(evidence);
    services.set(service, bucket);
  };

  const externals = new Set<string>();
  for (const entry of args.deps?.entries ?? []) {
    for (const external of entry.externals) externals.add(external);
  }
  for (const packageName of [...externals].sort()) {
    const service = SERVICE_BY_PACKAGE[packageName];
    if (service !== undefined) add(service, `imports ${packageName}`);
  }

  for (const entry of args.config?.entries ?? []) {
    for (const [pattern, service] of SERVICE_BY_ENV_PREFIX) {
      if (pattern.test(entry.name)) add(service, `env ${entry.name}`);
    }
  }

  if (services.size === 0) {
    return `${HEADER}\ngraph LR\n  empty[${label('No external services were identified')}]\n`;
  }

  const app = nodeId('svc', args.projectName);
  const lines = [HEADER, 'graph LR', `  ${app}[${label(args.projectName)}]`];

  for (const service of [...services.keys()].sort()) {
    const evidence = [...(services.get(service) ?? [])].sort();
    lines.push(`  ${nodeId('ext', service)}[${label(service)}]`);
    lines.push(`  ${app} --> |${label(evidence[0] as string)}| ${nodeId('ext', service)}`);
  }

  return `${lines.join('\n')}\n`;
}

