import fg from 'fast-glob';
import fs from 'node:fs/promises';
import path from 'node:path';
import YAML from 'yaml';
import { z } from 'zod';
import { DocgenError, describeUnknownError } from '../util/errors.js';
import { ANSWERS_DIR } from '../config/paths.js';
import { toPosix } from '../util/paths.js';
import { compareStrings } from '../util/sort.js';
import { writeFileAtomically } from '../util/atomic.js';
import { assertGeneratedPath } from '../util/generated.js';
import { assertUniqueHumanValues, humanRecordSlugSchema, parseHumanRecord } from '../util/human-records.js';

const answerSchema = z.object({
  questionId: z.string().min(1),
  question: z.string().default(''),
  answer: z.string().min(1),
  answeredBy: z.string().default('unknown'),
  answeredAt: z.string().default(''),
  note: z.string().optional(),
}).strict();

const surfaceAnswersSchema = z.object({
  surfaceId: z.string().min(1),
  slug: humanRecordSlugSchema.optional(),
  answers: z.array(answerSchema).default([]),
}).strict();

/**
 * Developer answers, on record.
 *
 * This is the most important file docgen writes. An answer here is the only
 * thing that promotes a claim from `inferred` to `verified`, and it must
 * survive refactors, regenerations, and prompt changes — so it is stored as
 * plain YAML in the repository, keyed by surface and question, readable and
 * editable by hand, and never regenerated by the tool.
 */

export interface Answer {
  /** Matches the `id` of the unknown it answers. */
  readonly questionId: string;
  readonly question: string;
  /** What the developer said. */
  readonly answer: string;
  /** Who answered — git identity, so a reader can follow up. */
  readonly answeredBy: string;
  /** ISO-8601. */
  readonly answeredAt: string;
  /** Free-text elaboration, when the developer added one. */
  readonly note?: string;
}

export interface SurfaceAnswers {
  readonly surfaceId: string;
  readonly slug: string;
  readonly answers: readonly Answer[];
  readonly sourceFile?: string;
}

/** Answers live beside the docs but are authored by humans, not generated. */
export { ANSWERS_DIR } from '../config/paths.js';

function answerFile(root: string, slug: string): string {
  return path.join(root, ANSWERS_DIR, `${slug}.yaml`);
}

/**
 * Load every recorded answer, keyed by surface id.
 *
 * A corrupt answer file is a loud error. These are ground truth: silently
 * ignoring one would demote confirmed knowledge back to a guess without anyone
 * noticing.
 */
export async function loadAnswers(root: string): Promise<ReadonlyMap<string, SurfaceAnswers>> {
  const files = (
    await fg([`${ANSWERS_DIR}/*.yaml`, `${ANSWERS_DIR}/*.yml`], { cwd: root, onlyFiles: true })
  )
    .map(toPosix)
    .sort(compareStrings);

  const bySurface = new Map<string, SurfaceAnswers>();

  for (const relative of files) {
    await assertGeneratedPath(root, relative);
    const absolute = path.join(root, relative);
    let parsed: unknown;
    try {
      parsed = YAML.parse(await fs.readFile(absolute, 'utf8'));
    } catch (cause) {
      throw new DocgenError({
        code: 'answers-unparseable',
        message: `${relative} is not valid YAML: ${describeUnknownError(cause)}`,
        remedy:
          'Fix the YAML syntax. These files are recorded developer answers and are treated as ' +
          'ground truth, so docgen will not skip one it cannot read.',
        file: relative,
        cause,
      });
    }

    const record = parseHumanRecord(surfaceAnswersSchema, parsed, relative, 'answers');
    const slug = record.slug ?? path.posix.basename(relative, path.posix.extname(relative));
    parseHumanRecord(humanRecordSlugSchema, slug, relative, 'answers');
    assertUniqueHumanValues(record.answers.map(answer => answer.questionId), relative, 'answers');
    if (bySurface.has(record.surfaceId)) {
      throw new DocgenError({ code: 'answers-duplicate-surface', message: `${relative} duplicates answers for '${record.surfaceId}'.`, remedy: 'Merge the conflicting human records into one file without discarding answers.', file: relative });
    }
    const answers: Answer[] = record.answers.map(({ note, ...fields }) => ({ ...fields, ...(note === undefined ? {} : { note }) }));
    bySurface.set(record.surfaceId, { surfaceId: record.surfaceId, slug, answers, sourceFile: relative });
  }

  return bySurface;
}

/**
 * Record an answer, merging into whatever is already on file.
 *
 * Re-answering a question replaces the previous answer rather than appending:
 * two conflicting answers to one question would leave a reader with no way to
 * tell which is current.
 */
export async function recordAnswer(args: {
  root: string;
  surfaceId: string;
  slug: string;
  answer: Answer;
}): Promise<void> {
  parseHumanRecord(surfaceAnswersSchema, { surfaceId: args.surfaceId, slug: args.slug, answers: [args.answer] }, `${ANSWERS_DIR}/${args.slug}.yaml`, 'answers');
  const existing = (await loadAnswers(args.root)).get(args.surfaceId);
  const kept = (existing?.answers ?? []).filter(
    (candidate) => candidate.questionId !== args.answer.questionId,
  );

  const merged: SurfaceAnswers = {
    surfaceId: args.surfaceId,
    slug: existing?.slug ?? args.slug,
    answers: [...kept, args.answer].sort((a, b) => compareStrings(a.questionId, b.questionId)),
  };

  const file = existing?.sourceFile === undefined ? answerFile(args.root, args.slug) : path.join(args.root, existing.sourceFile);
  await assertGeneratedPath(args.root, toPosix(path.relative(args.root, file)));
  await writeFileAtomically(file, renderAnswersFile(merged));
}

/** YAML with a header explaining what the file is for, since humans edit it. */
export function renderAnswersFile(surface: SurfaceAnswers): string {
  const header = [
    '# Developer answers recorded by docgen.',
    '#',
    '# These are ground truth. Every answer here promotes a section of the',
    '# generated documentation from "inferred by a model" to "verified".',
    '# Edit by hand if an answer was wrong — docgen never overwrites this file',
    '# except to add or replace an answer you gave it.',
    '',
  ].join('\n');

  return `${header}${YAML.stringify(
    {
      surfaceId: surface.surfaceId,
      slug: surface.slug,
      answers: surface.answers.map((answer) => ({
        questionId: answer.questionId,
        question: answer.question,
        answer: answer.answer,
        answeredBy: answer.answeredBy,
        answeredAt: answer.answeredAt,
        ...(answer.note === undefined ? {} : { note: answer.note }),
      })),
    },
    { lineWidth: 100 },
  )}`;
}

/** The answers for one surface, rendered for injection into a prompt. */
export function renderAnswersForPrompt(answers: readonly Answer[]): string {
  if (answers.length === 0) return '_None yet._';
  return answers
    .map((answer) => `- **${answer.question || answer.questionId}** → ${answer.answer} _(${answer.answeredBy})_`)
    .join('\n');
}
